#!/usr/bin/env node
// Inline the palette into a generated module.
//
// It has to reach the browser inside the document <head>, before the deferred
// stylesheet loads, or a dark-mode visitor gets a frame of the light palette.
// It is authored as a real stylesheet (src/theme-tokens.css) so it can be
// edited and linted as one, and inlined verbatim here. Generated and
// git-ignored; runs as pre{start,build}.
//
// Only the stylesheet is inlined. A site with a theme toggle also needs a
// pre-paint SCRIPT here, to read the stored preference and set `data-theme`
// before anything renders; this one has no toggle, no stored preference and no
// JavaScript at all, so its only theme signal is `prefers-color-scheme`, which
// CSS answers by itself. There is deliberately no THEME_PREPAINT_JS export and
// no src/theme-prepaint.js — not even an empty one, because an empty inline
// <script> is still a <script> tag in the published HTML.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { REPO_ROOT } from './lib/site-content.mjs';

const tokensPath = resolve(REPO_ROOT, 'src/theme-tokens.css');

const tokens = readFileSync(tokensPath, 'utf8');

// Cheap shape checks, so a rename or a bad edit fails the build here rather
// than shipping a page with no palette and a silent light flash. The second
// one is what keeps the dark palette from being dropped: without the media
// query there is no dark mode at all, and the page still looks correct to
// whoever is testing it in light mode.
if (!tokens.includes('--bg:')) {
  throw new Error(`${tokensPath} defines no --bg token`);
}
if (!tokens.includes('prefers-color-scheme: dark')) {
  throw new Error(`${tokensPath} has no dark-scheme block`);
}

const out = resolve(REPO_ROOT, 'app/generated/theme-prelude.ts');
mkdirSync(resolve(REPO_ROOT, 'app/generated'), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/extract-theme-prelude.mjs from src/theme-tokens.css.
// Do not edit; git-ignored.

export const THEME_TOKENS_CSS = ${JSON.stringify(tokens)};
`,
);
console.log(`theme prelude: ${tokens.length} B tokens`);
